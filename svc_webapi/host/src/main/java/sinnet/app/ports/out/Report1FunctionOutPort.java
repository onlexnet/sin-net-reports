package sinnet.app.ports.out;

import java.time.Instant;

import com.fasterxml.jackson.annotation.JsonProperty;

import sinnet.report1.grpc.ReportRequests;

/**
 * Port-out interface for calling Azure Function implementation of report1.
 */
public interface Report1FunctionOutPort {

  /**
   * Requests report generation from fun_report1 and returns a time-limited download link.
   *
   * @param request the report data
   * @param downloadFileName the desired filename for the generated archive, e.g. {@code "report 2024-3.zip"}
   * @return a SAS link to the generated ZIP archive and its expiry timestamp
   */
  ReportLink producePack(ReportRequests request, String downloadFileName);

  /**
   * A time-limited download link to a report generated by fun_report1.
   *
   * <p>Serialized as {@code expires_at} (not {@code expiresAt}) to keep the JSON shape returned
   * to browser clients identical to fun_report1's own {@code ReportLinkResponse} contract.
   *
   * @param url the SAS URL granting read-only access to the generated report
   * @param expiresAt the timestamp after which the URL no longer grants access
   */
  record ReportLink(String url, @JsonProperty("expires_at") Instant expiresAt) {
  }
}
